/// مساعدات عرض أسماء الصيدليات.
///
/// بعض صفحات الإدارة تحفظ اسم الصيدلية كما هو مكتوب (قد يبدأ بـ«صيدلية»)،
/// وواجهات العميل تضيف «صيدلية » تلقائياً قبل الاسم → النتيجة ازدواج مثل
/// «صيدلية صيدلية مصطفى». هذه الدالة تمنع الازدواج دون تغيير القاعدة.
final RegExp _hasShopPrefix = RegExp(r'^صيدلية(\s|$)');

/// اسم الصيدلية جاهزاً للعرض داخل الجمل: «صيدلية X» —
/// وإذا كان الاسم نفسه يبدأ بـ«صيدلية» يُعرض كما هو.
String shopDisplayName(String name) {
  final n = name.trim();
  if (n.isEmpty) return 'صيدلية';
  return _hasShopPrefix.hasMatch(n) ? n : 'صيدلية $n';
}
